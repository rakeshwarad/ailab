# 8-Puzzle using Depth-Limited Search and Iterative Deepening Search

def get_neighbors(state):
    """Generate all possible moves of the blank space."""
    neighbors = []

    zero = state.index(0)
    row = zero // 3
    col = zero % 3

    moves = [
        (-1, 0, "UP"),
        (1, 0, "DOWN"),
        (0, -1, "LEFT"),
        (0, 1, "RIGHT")
    ]

    for dr, dc, move in moves:
        new_row = row + dr
        new_col = col + dc

        if 0 <= new_row < 3 and 0 <= new_col < 3:
            new_zero = new_row * 3 + new_col

            new_state = list(state)
            new_state[zero], new_state[new_zero] = \
                new_state[new_zero], new_state[zero]

            neighbors.append((tuple(new_state), move))

    return neighbors


def depth_limited_search(state, goal, limit, path, moves):
    # Goal test
    if state == goal:
        return moves

    # Depth limit reached
    if limit == 0:
        return None

    # Generate next states
    for next_state, move in get_neighbors(state):

        # Avoid states already in current path
        if next_state not in path:
            path.add(next_state)
            result = depth_limited_search(
                next_state,
                goal,
                limit - 1,
                path,
                moves + [move]
            )

            if result is not None:
                return result

            path.remove(next_state)

    return None


def iterative_deepening_search(initial, goal, max_depth=30):
    depth = 0

    while depth <= max_depth:
        print("Searching at depth:", depth)

        path = {initial}

        result = depth_limited_search(
            initial,
            goal,
            depth,
            path,
            []
        )

        if result is not None:
            return result, depth

        depth += 1

    return None, None


# -------------------------
# Main Program
# -------------------------

initial = (
    1, 2, 3,
    0, 4, 6,
    7, 5, 8
)

goal = (
    1, 2, 3,
    4, 5, 6,
    7, 8, 0
)

# IDS
solution, depth = iterative_deepening_search(initial, goal)

if solution:
    print("\nSolution Found!")
    print("Moves:", " -> ".join(solution))
    print("Depth:", depth)
else:
    print("\nSolution not found.")